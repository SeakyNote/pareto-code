import assert from 'node:assert/strict';
import { once } from 'node:events';
import { existsSync } from 'node:fs';
import { mkdir, readFile } from 'node:fs/promises';
import { createApp } from '../server/app.js';
import { createStore } from '../server/store.js';
import { fixture } from '../tests/helpers.js';

let chromium;
try { ({ chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')); }
catch {
  console.error('浏览器检查需要 Playwright。可先执行 npm install --no-save playwright，再运行 npm run test:browser。也可用 PLAYWRIGHT_MODULE_PATH 指向已有的 playwright/index.mjs。');
  process.exit(1);
}
const store = createStore(':memory:');
const server = createApp(store);
let browser, page;
let checks = 0;
const checked = (message) => { checks++; console.log(`✓ ${message}`); };
try {
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const executablePath = process.env.BROWSER_EXECUTABLE || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined);
  browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
  const pageErrors = [], dialogs = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  page.on('dialog', async (dialog) => { dialogs.push(dialog.message()); await dialog.dismiss(); });
  await mkdir('test-results', { recursive: true });
  const analyzed = async (action) => {
    const response = page.waitForResponse((res) => res.url().includes('/api/analyze?') && res.ok());
    await action(); await response;
    await page.waitForFunction(() => !document.querySelector('#export-report').disabled);
  };
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForSelector('.chart-point');
  assert.equal(await page.locator('.chart-point').count(), 16);
  assert.equal(await page.locator('#config-table tr').count(), 18);
  assert.match(await page.locator('#data-notice').innerText(), /演示数据/);
  checked('默认场景、数据来源、16 个可比配置及 2 个待补齐配置');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  checked('桌面布局无页面横向溢出，保存截图');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  await page.locator('#menu-toggle').click();
  await page.locator('.nav-item[data-view="method"]').click();
  await page.locator('#view-method').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#view-method').isVisible(), true);
  await page.locator('#menu-toggle').click();
  await page.locator('.nav-item[data-view="workbench"]').click();
  await page.locator('#view-workbench').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#view-workbench').isVisible(), true);
  checked('手机布局、侧栏导航与方法页面');
  await page.setViewportSize({ width: 1440, height: 1080 });
  for (const id of ['luna-low', 'luna-medium', 'luna-high', 'luna-xhigh', 'sol-high']) await page.locator(`#config-table [data-pin="${id}"]`).click();
  assert.equal(await page.locator('.compare-card').count(), 5);
  await page.locator('#config-table [data-pin="terra-high"]').click();
  assert.equal(await page.locator('.compare-card').count(), 5);
  assert.match(await page.locator('#toast').innerText(), /最多对比 5/);
  checked('配置对比、五个配置上限及提示');
  await page.locator('#clear-comparison').click();
  await page.locator('.chart-point[data-record-id="sol-high"]').click();
  assert.equal(await page.locator('.compare-card').count(), 1);
  await page.reload(); await page.waitForSelector('.chart-point');
  assert.equal(await page.locator('.compare-card').count(), 1);
  checked('点击图表加入对比，刷新后恢复选择');
  await page.locator('[data-table-filter="excluded"]').click();
  assert.equal(await page.locator('#config-table tr').count(), 2);
  await page.locator('[data-table-filter="all"]').click();
  await page.locator('[data-sort="quality"]').click();
  assert.equal(await page.locator('#config-table tr').first().getAttribute('data-row-id'), 'sol-high');
  await page.locator('#table-search').fill('没有这个模型');
  assert.match(await page.locator('#config-table').innerText(), /没有配置/);
  await page.locator('#table-search').fill('');
  checked('数据范围、数值排序、搜索与空列表');
  await page.locator('#config-table [data-detail="luna-high"]').click();
  assert.match(await page.locator('#detail-content').innerText(), /MVP 人工构造演示集/);
  assert.match(await page.locator('#detail-content').innerText(), /wall-clock/);
  await page.keyboard.press('Escape');
  checked('配置详情包含版本、来源和完整统计口径');
  await page.locator('#chart-x').selectOption('duration');
  await page.locator('[data-scale="log"]').click();
  assert.match(await page.locator('.scatter-chart').getAttribute('aria-label'), /执行耗时/);
  assert.doesNotMatch(await page.locator('.scatter-chart').innerHTML(), /NaN|Infinity/);
  await page.locator('#only-front').check();
  assert.equal(await page.locator('.chart-point').count(), 13);
  await page.locator('#only-front').uncheck();
  checked('费用与耗时投影、对数坐标、仅前沿开关');
  await page.locator('#max-cost').fill('0');
  await page.locator('#max-duration').fill('1');
  await page.locator('#min-quality').fill('100');
  await analyzed(() => page.locator('#analyze-button').click());
  assert.match(await page.locator('#recommendations').innerText(), /暂无配置同时满足条件/);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-report').click();
  const report = await downloadPromise;
  const reportPath = await report.path();
  const reportText = await readFile(reportPath, 'utf8');
  assert.match(reportText, /没有配置同时满足/); assert.match(reportText, /\$0.00/);
  checked('冲突约束显示空推荐，导出的报告保留零预算');
  await analyzed(() => page.locator('#reset-filters').click());
  assert.match(await page.locator('#analysis-status').innerText(), /8 个配置满足/);
  await analyzed(() => page.locator('[data-channel="subscription"]').click());
  assert.equal(await page.locator('#config-table tr').count(), 4);
  assert.equal(await page.locator('#subscription-fields').isVisible(), true);
  await page.locator('#monthly-price').fill('30');
  await page.locator('#monthly-tasks').fill('300');
  await analyzed(() => page.locator('#analyze-button').click());
  assert.match(await page.locator('#config-table').innerText(), /\$0.10/);
  checked('API 与订阅隔离，月费和任务量实时重新折算');
  await page.locator('.top-actions [data-action="import"]').click();
  await page.locator('#import-text').fill('{');
  await page.locator('#preview-import').click();
  await page.waitForFunction(() => document.querySelector('#import-feedback').textContent.includes('JSON 格式无效'));
  assert.equal(await page.locator('#commit-import').isDisabled(), true);
  checked('无效数据阻止确认导入，并展示校验错误');
  const imported = fixture('browser-import');
  imported.benchmark.scenario = 'svg'; imported.benchmark.currency = 'CNY'; imported.benchmark.source.name = '浏览器测试来源';
  imported.records[0].model = '<img src=x onerror=alert(1)>';
  imported.benchmark.name = 'SVG 测试 <svg onload=alert(2)>';
  await page.locator('#import-text').fill(JSON.stringify(imported));
  await page.locator('#preview-import').click();
  await page.waitForFunction(() => !document.querySelector('#commit-import').disabled);
  assert.match(await page.locator('#import-feedback').innerText(), /校验通过，尚未写入/);
  assert.equal((await store.listBenchmarks()).length, 1);
  await analyzed(() => page.locator('#commit-import').click());
  assert.equal(await page.locator('#import-dialog').isVisible(), false);
  assert.match(await page.locator('#benchmark-select').innerText(), /SVG 测试/);
  assert.match(await page.locator('#config-table').innerText(), /¥1.00/);
  assert.equal(await page.locator('[data-channel="api"]').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('[data-channel="subscription"]').isDisabled(), true);
  assert.equal(store.listBenchmarks().length, 2);
  checked('预览无写入，确认后新场景、币种与可用渠道自动生效');
  assert.equal(await page.locator('#config-table img').count(), 0);
  assert.deepEqual(dialogs, []);
  checked('导入的 HTML 标签作为文本展示，不执行脚本');
  await page.locator('.nav-item[data-view="data"]').click();
  assert.equal(await page.locator('.dataset-card').count(), 2);
  assert.match(await page.locator('#import-history').innerText(), /粘贴数据导入/);
  checked('数据管理页展示独立快照与导入历史');
  assert.deepEqual(pageErrors, []);
  checked('全部流程没有未捕获的浏览器异常');
  console.log(`浏览器检查通过：${checks} 项；截图位于 test-results/desktop.png 与 test-results/mobile.png。`);
} catch (error) {
  if (page && !page.isClosed()) await page.screenshot({ path: 'test-results/browser-failure.png', fullPage: true });
  throw error;
} finally {
  await browser?.close();
  if (server.listening) { server.close(); server.closeAllConnections(); await once(server, 'close'); }
  store.close();
}
